#!/usr/bin/env python3
"""Writes the operand table of Mac/Shaders/SpirvIdentity.cpp from Khronos' SPIR-V grammar.

usage: make_spirv_operands.py <spirv.core.grammar.json> <out.inc>

One line per instruction: its opcode and a pattern, one letter per operand.

  T  result type id        R  result id          i  id            l  literal word
  s  string                c  literal words to the end of the instruction
  P  (literal, id) pairs   D  decoration, then its literal parameters
  I  image operands mask, then ids               M  memory access mask, then literals
  E  execution mode, then literals               L  loop control mask, then literals
  X  not supported: an instruction with this operand present is refused

A letter may be followed by ? (optional) or * (any number).
"""

import json
import sys

ID_KINDS = {"IdRef", "IdScope", "IdMemorySemantics"}
LITERAL_KINDS = {"LiteralInteger", "LiteralFloat", "LiteralExtInstInteger", "LiteralSpecConstantOpInteger"}
PARAMETRIC = {"Decoration": "D", "ImageOperands": "I", "MemoryAccess": "M", "ExecutionMode": "E", "LoopControl": "L"}
# Their parameters are ids or strings, which the letters above would misread.
REFUSED = {"OpDecorateId", "OpExecutionModeId", "OpSpecConstantOp", "OpGroupDecorate", "OpGroupMemberDecorate",
           "OpDecorationGroup", "OpTypeForwardPointer"}


def main():
    grammar = json.load(open(sys.argv[1]))
    kinds = {k["kind"]: k for k in grammar["operand_kinds"]}

    def has_parameters(kind):
        return any(e.get("parameters") for e in kinds[kind].get("enumerants", []))

    def letter(kind):
        if kind == "IdResultType":
            return "T"
        if kind == "IdResult":
            return "R"
        if kind in ID_KINDS:
            return "i"
        if kind in LITERAL_KINDS:
            return "l"
        if kind == "LiteralString":
            return "s"
        if kind == "LiteralContextDependentNumber":
            return "c"
        if kind == "PairLiteralIntegerIdRef":
            return "P"
        if kind == "PairIdRefIdRef":
            return "ii"
        if kind in PARAMETRIC:
            return PARAMETRIC[kind]
        category = kinds[kind]["category"]
        if category in ("ValueEnum", "BitEnum") and not has_parameters(kind):
            return "l"
        return "X"

    lines = []
    seen = set()
    for inst in grammar["instructions"]:
        opcode = inst["opcode"]
        if opcode in seen:      # an alias of an earlier name
            continue
        seen.add(opcode)
        pattern = ""
        if inst["opname"] in REFUSED:
            pattern = "X"
        else:
            for operand in inst.get("operands", []):
                l = letter(operand["kind"])
                quantifier = operand.get("quantifier", "")
                if len(l) == 2:     # a pair of ids
                    l = "i" if quantifier else "ii"
                pattern += l + quantifier
        lines.append('    { %d, "%s" },     // %s\n' % (opcode, pattern, inst["opname"]))

    with open(sys.argv[2], "w") as out:
        out.write("// Generated by Mac/Shaders/make_spirv_operands.py from SPIRV-Headers' spirv.core.grammar.json. Do not edit.\n")
        out.writelines(lines)


if __name__ == "__main__":
    main()
